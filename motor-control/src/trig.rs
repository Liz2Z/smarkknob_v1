/// Inputs in this firmware are bounded electrical angles, at most ~50 rad.
/// Keep libm as a fallback for non-finite or unusually large external inputs.
pub(crate) fn sin(angle: f32) -> f32 {
    let phase = angle * (256.0 / TAU);
    if !phase.is_finite() || phase.abs() > 1_000_000.0 {
        return libm::sinf(angle);
    }
    let truncated = phase as i32;
    let index = if phase < truncated as f32 {
        truncated - 1
    } else {
        truncated
    };
    let fraction = phase - index as f32;
    let a = SIN[(index & 255) as usize];
    let b = SIN[((index + 1) & 255) as usize];
    a + (b - a) * fraction
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn control_angles_match_reference_with_sub_pwm_count_error() {
        for i in -100_000..=100_000 {
            let angle = i as f32 / 1000.0;
            // Linear interpolation error < 8e-5, including range-rounding.
            // At a 12V bus and 1V command this is < 0.02 PWM counts.
            assert!((sin(angle) - libm::sinf(angle)).abs() < 0.00009, "{angle}");
        }
        assert!(sin(f32::NAN).is_nan());
    }
}
